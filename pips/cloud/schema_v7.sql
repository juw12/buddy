CREATE TABLE IF NOT EXISTS duels (
  id TEXT PRIMARY KEY,
  mode TEXT NOT NULL DEFAULT 'live',
  status TEXT NOT NULL DEFAULT 'pending',
  a_id TEXT NOT NULL,
  b_id TEXT NOT NULL,
  a_stats TEXT NOT NULL DEFAULT '{}',
  b_stats TEXT NOT NULL DEFAULT '{}',
  a_hp INTEGER NOT NULL DEFAULT 0,
  b_hp INTEGER NOT NULL DEFAULT 0,
  a_charge INTEGER NOT NULL DEFAULT 0,
  b_charge INTEGER NOT NULL DEFAULT 0,
  a_act TEXT,
  b_act TEXT,
  a_miss INTEGER NOT NULL DEFAULT 0,
  b_miss INTEGER NOT NULL DEFAULT 0,
  round INTEGER NOT NULL DEFAULT 0,
  deadline INTEGER NOT NULL DEFAULT 0,
  log TEXT NOT NULL DEFAULT '[]',
  winner TEXT,
  result TEXT NOT NULL DEFAULT '{}',
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS duels_status ON duels (status, updated_at);
CREATE INDEX IF NOT EXISTS duels_a ON duels (a_id, status);
CREATE INDEX IF NOT EXISTS duels_b ON duels (b_id, status);
